"""Pinned DC-link recheck. Missing dependencies remain recorded failures."""
import json
import os
import shutil
import subprocess
import tarfile
import time
from pathlib import Path
from lab.evidence import check_case
from lab.evidence.checker import digest
from .runner import ROOT, PYTHON, run, export_case, write_json

REVISION = 'be9a0f4'
SOURCE = 'external/dclink-simulator'


def leaves(obj, prefix=''):
    for key, value in obj.items():
        key = prefix + key
        if isinstance(value, dict):
            yield from leaves(value, key + '.')
        else:
            yield key, value


def build_case(records, name, started, sha, diagnostic=False):
    case = ROOT / 'cases' / name
    case.mkdir(parents=True, exist_ok=True)
    claims = []
    lines = ['# DC-link 固定版本复核', '', '固定源码版本：`be9a0f4`。以下数值来自本次实际运行。']
    if diagnostic:
        lines += ['', '本例固件部分为直接执行 GCC 编译与测试命令的补充诊断，不是 GNU make 运行。']
    lines += ['', '## 结果']
    for index, rec in enumerate(records):
        metrics = json.loads((ROOT / 'runs' / rec['run_id'] / 'metrics.json').read_text())
        for key, value in leaves(metrics):
            cid = ('fw_' if index == 0 else 'py_') + key
            claims.append({'id': cid, 'kind': 'metric', 'text': key, 'value': value, 'unit': '',
                           'run_id': rec['run_id'], 'metric_key': key})
            lines.append(f"- `{key}`：{value}⟦c:{cid}⟧")
    if any(r['exit_code'] or r.get('parse_error') for r in records):
        lines += ['', '## 限制', '至少一次命令未成功；此案例保留失败证据，不能作为通过的复核。']
    write_json(case / 'claims.json', claims)
    (case / 'report.md').write_text('\n'.join(lines) + '\n', encoding='utf-8')
    for rec in records:
        export_case(case, [rec['run_id']], case / 'claims.json', case / 'report.md')
    result = check_case(case)
    write_json(case / 'check.json', result)
    write_json(case / 'timing.json', {'total_duration_s': time.monotonic() - started,
               'peak_rss_mb': max(r['peak_rss_mb'] for r in records),
               'measurement': 'serial jobs; sampled process-tree RSS with kernel high-water mark; may miss aggregate short peaks',
               'runs': [r['run_id'] for r in records], 'source_git_sha': sha})
    return result


def dclink_check(diagnose_missing_make=False):
    started = time.monotonic()
    dest = ROOT / 'data/dclink_src'
    marker = dest / '.ev_archive_revision'
    if dest.exists():
        if not marker.is_file() or marker.read_text().strip() != REVISION or dest.is_symlink():
            raise ValueError('data/dclink_src exists without matching archive marker; refusing to overwrite')
        # This directory is generated by this command; preserve previous run artifacts in runs/.
        shutil.rmtree(dest)
    dest.mkdir(parents=True)
    archive = subprocess.Popen(['git', '-C', SOURCE, 'archive', REVISION], stdout=subprocess.PIPE)
    try:
        with tarfile.open(fileobj=archive.stdout, mode='r|') as tar:
            for member in tar:
                if member.issym() or member.islnk() or member.name.startswith('/') or '..' in Path(member.name).parts:
                    raise ValueError('unsafe archive member: ' + member.name)
                tar.extract(member, dest, filter='data')
    finally:
        archive.stdout.close()
    if archive.wait() != 0:
        raise ValueError('git archive failed')
    marker.write_text(REVISION + '\n')
    sha = subprocess.check_output(['git', '-C', SOURCE, 'rev-parse', REVISION], text=True).strip()
    # Manifest of all archived bytes, before any build or test writes.
    manifest = ROOT / 'data/dclink_src_manifest.json'
    write_json(manifest, {str(p.relative_to(dest)): digest(p) for p in sorted(dest.rglob('*'))
                          if p.is_file() and p != marker})
    env = {'PATH': str(Path(PYTHON).parent) + os.pathsep + os.environ.get('PATH', ''),
           'NUMBA_CACHE_DIR': str(ROOT / 'data/dclink_numba_cache'), 'PYTEST_DISABLE_PLUGIN_AUTOLOAD': '1'}
    def execute(name, cmd, cwd, parser, extra_inputs=()):
        print('Running ' + name, flush=True)
        rec = run(name, cmd, inputs=[manifest, *extra_inputs], parser=parser, cwd=cwd, env=env, git_sha=sha)
        print(f"{name}: exit={rec['exit_code']}, duration={rec['duration_s']:.3f}s, peak RSS={rec['peak_rss_mb']:.2f} MiB", flush=True)
        if rec.get('parse_error'):
            print('Parser error: ' + rec['parse_error'], flush=True)
        return rec
    firmware = execute('dclink-fw', ['make', '-C', 'data/dclink_src/fw', 'clean', 'test', 'replay', 'check'], ROOT, 'fw')
    diagnostic = None
    if diagnose_missing_make and firmware['exit_code'] == 127 and shutil.which('make', path=env['PATH']) is None:
        print('GNU make unavailable; running explicitly labeled supplemental diagnostic.', flush=True)
        diagnostic = execute('dclink-fw-direct-diagnostic', [PYTHON, '-m', 'lab.repro.fw_diagnostic'], ROOT, 'fw',
                             [ROOT / 'lab/repro/fw_diagnostic.py'])
    python_tests = execute('dclink-python', [PYTHON, '-m', 'pytest', 'sim/tests', 'simsw/tests', '-q'], dest, 'pytest')
    result = build_case([firmware, python_tests], 'dclink_recheck', started, sha)
    print('Required recheck evidence verdict: ' + result['verdict'], flush=True)
    if diagnostic:
        supplemental = build_case([diagnostic, python_tests], 'dclink_diagnostic', started, sha, diagnostic=True)
        print('Supplemental direct-build evidence verdict: ' + supplemental['verdict'], flush=True)
    return int(result['verdict'] != 'pass' or any(r.get('parse_error') or r['exit_code'] for r in (firmware, python_tests)))
